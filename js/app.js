const llista = document.getElementById("llista-cancons");

cancons.sort((a, b) => a.titol.localeCompare(b.titol, "es"));

cancons.forEach(canço => {

    // Creem un botó
    const boto = document.createElement("button");
    boto.textContent = canço.titol;

    // Creem un espai per a la lletra
    const lletra = document.createElement("p");
    lletra.textContent = canço.lletra;
    lletra.classList.add("ocult");

    // Quan premem el botó, mostrem o amaguem la lletra
    boto.addEventListener("click", function() {
        lletra.classList.toggle("ocult");
    });

    // Afegim el botó i la lletra a la llista
    const element = document.createElement("li");
    element.appendChild(boto);
    element.appendChild(lletra);

    llista.appendChild(element);
});
